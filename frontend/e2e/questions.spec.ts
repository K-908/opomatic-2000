import { expect, test } from '@playwright/test'

test('P07: bank and forms against PHP, validation, search, edit and status', async ({ page }) => {
  await page.goto('/questions')
  await page.getByLabel('Nombre de usuario').fill('Gogloglo')
  await page.getByLabel('Contraseña').fill(process.env.OPOMATIC_E2E_GOGLOGLO_PASSWORD ?? '')
  await page.getByRole('button', { name: 'Iniciar sesión' }).click()
  await expect(page.getByRole('heading', { name: 'Preguntas', exact: true })).toBeVisible()
  await expect(page.getByText('No hay preguntas', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Nueva pregunta', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar pregunta', exact: true }).click()
  await expect(page.getByText('Selecciona un tema.', { exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Tema', exact: true })).toBeFocused()
  await page.getByRole('combobox', { name: 'Tema', exact: true }).selectOption({ label: 'Tema P07' })
  await page.getByLabel('Enunciado').fill('P07 capital de España')
  for (let position = 1; position <= 4; position += 1) {
    await page.getByLabel(`Opción ${position}`, { exact: true }).fill(`Respuesta ${position}`)
  }
  await page.getByLabel('Opción 2 correcta', { exact: true }).check()
  // Send an invalid option to the real backend to verify its field error and focus.
  await page.route('**/api/questions', route => {
    const body = route.request().postDataJSON()
    body.options[0].text = ' '
    return route.continue({ postData: JSON.stringify(body) })
  }, { times: 1 })
  await page.getByRole('button', { name: 'Guardar pregunta', exact: true }).click()
  await expect(page.getByText('El texto de cada opción es obligatorio y no puede superar los 1.000 caracteres.')).toBeVisible()
  await expect(page.getByLabel('Opción 1', { exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Guardar pregunta', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pregunta guardada', exact: true })).toBeFocused()
  await page.getByRole('link', { name: 'Volver al banco', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'P07 capital de España', exact: true })).toBeVisible()
  await page.getByLabel('Texto', { exact: true }).fill('No coincide')
  await page.keyboard.press('Enter')
  await expect(page.getByText('No hay preguntas', { exact: true })).toBeVisible()
  await page.getByLabel('Texto', { exact: true }).fill('capital')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'P07 capital de España', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Tema', exact: true }).selectOption({ label: 'Otro tema P07' })
  await expect(page.getByText('No hay preguntas', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Tema', exact: true }).selectOption({ label: 'Tema P07' })
  await page.getByRole('link', { name: 'Editar P07 capital de España', exact: true }).click()
  await expect(page.getByLabel('Enunciado')).toHaveValue('P07 capital de España')
  await expect(page.getByLabel('Opción 2 correcta', { exact: true })).toBeChecked()
  await page.getByLabel('Enunciado').fill('P07 capital revisada')
  await page.getByLabel('Opción 4 correcta', { exact: true }).check()
  await page.getByRole('button', { name: 'Guardar pregunta', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pregunta guardada', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Volver al banco', exact: true }).click()
  await expect(page.getByLabel('Texto', { exact: true })).toHaveValue('capital')
  await expect(page.getByRole('heading', { name: 'P07 capital revisada', exact: true })).toBeVisible()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: 'Desactivar P07 capital revisada', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'P07 capital revisada', exact: true })).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Desactivar P07 capital revisada', exact: true }).click()
  await expect(page.getByText('No hay preguntas', { exact: true })).toBeVisible()
  await page.getByLabel('Mostrar inactivas').check()
  await expect(page.getByText('Inactiva', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reactivar P07 capital revisada', exact: true }).click()
  await expect(page.getByText('Inactiva', { exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'P07 capital revisada', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Editar P07 capital revisada', exact: true }).click()
  await expect(page.getByLabel('Opción 4 correcta', { exact: true })).toBeChecked()
  await page.getByRole('link', { name: 'Cancelar', exact: true }).click()
  await page.route('**/api/questions?*', async route => { await new Promise(resolve => setTimeout(resolve, 500)); await route.continue() })
  await page.getByLabel('Mostrar inactivas').uncheck()
  await expect(page.getByText('Cargando preguntas…', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'P07 capital revisada', exact: true })).toBeVisible()
  await page.unroute('**/api/questions?*')
  await page.route('**/api/questions?*', route => route.fulfill({ status: 500, contentType: 'application/problem+json', body: JSON.stringify({ title: 'Error temporal', status: 500 }) }))
  await page.getByLabel('Mostrar inactivas').check()
  await expect(page.getByText('No se han podido cargar las preguntas.', { exact: true })).toBeVisible()
})
