import { expect, test } from '@playwright/test'

test('P06: topics against PHP, keyboard, errors, create, edit and status', async ({ page }) => {
  await page.goto('/topics')
  await page.getByLabel('Nombre de usuario').fill('Gogloglo')
  await page.getByLabel('Contraseña').fill(process.env.OPOMATIC_E2E_GOGLOGLO_PASSWORD ?? '')
  await page.getByRole('button', { name: 'Iniciar sesión' }).click()
  await expect(page.getByRole('heading', { name: 'Temas', exact: true })).toBeVisible()
  await expect(page.getByText('Todavía no hay temas')).toBeVisible()
  await page.getByLabel('Nombre', { exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByText('El nombre del tema es obligatorio.')).toBeVisible()
  await expect(page.getByLabel('Nombre', { exact: true })).toBeFocused()
  await page.getByLabel('Nombre', { exact: true }).fill('Tema P06 navegador')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Tema P06 navegador', exact: true })).toBeVisible()
  await page.getByLabel('Nombre', { exact: true }).fill('TEMA P06 NAVEGADOR')
  await page.getByRole('button', { name: 'Crear tema', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Ya existe un tema')
  await page.getByRole('button', { name: 'Editar Tema P06 navegador', exact: true }).click()
  await expect(page.getByLabel('Nombre', { exact: true })).toBeFocused()
  await page.getByLabel('Nombre', { exact: true }).fill('Tema P06 editado')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Tema P06 editado', exact: true })).toBeVisible()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: 'Desactivar Tema P06 editado', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tema P06 editado', exact: true })).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Desactivar Tema P06 editado', exact: true }).click()
  await expect(page.getByText('Todavía no hay temas')).toBeVisible()
  await page.getByLabel('Mostrar inactivos').check()
  await expect(page.getByText('Inactivo', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reactivar Tema P06 editado', exact: true }).click()
  await expect(page.getByText('Inactivo', { exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Tema P06 editado', exact: true })).toBeVisible()
  await page.route('**/api/topics?*', async route => { await new Promise(resolve => setTimeout(resolve, 500)); await route.continue() })
  await page.getByLabel('Mostrar inactivos').check()
  await expect(page.getByRole('status')).toContainText('Cargando temas')
  await expect(page.getByRole('heading', { name: 'Tema P06 editado', exact: true })).toBeVisible()
  await page.unroute('**/api/topics?*')
  await page.route('**/api/topics?*', route => route.fulfill({ status: 500, contentType: 'application/problem+json', body: JSON.stringify({ title: 'Error temporal', status: 500 }) }))
  await page.getByLabel('Mostrar inactivos').uncheck()
  await expect(page.getByText('No se han podido cargar los temas. Comprueba la conexión con la API.')).toBeVisible()
})
