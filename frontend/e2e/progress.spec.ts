import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'

test('P11/P12: empty states, pagination, immutable review, updated metrics and errors against PHP', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Nombre de usuario').fill('Virginia')
  await page.getByLabel('Contraseña').fill(process.env.OPOMATIC_E2E_VIRGINIA_PASSWORD ?? '')
  await page.getByRole('button', { name: 'Iniciar sesión' }).click()
  await expect(page.getByRole('heading', { name: 'Empieza con tu primer test' })).toBeVisible()
  await page.goto('/attempts')
  await expect(page.getByRole('heading', { name: 'Todavía no has terminado ningún test' })).toBeVisible()
  await page.goto('/statistics')
  await expect(page.getByRole('heading', { name: 'Todavía no hay resultados por tema' })).toBeVisible()
  await page.getByRole('button', { name: 'Cerrar sesión' }).click()
  await page.getByLabel('Nombre de usuario').fill('Gogloglo')
  await page.getByLabel('Contraseña').fill(process.env.OPOMATIC_E2E_GOGLOGLO_PASSWORD ?? '')
  await page.getByRole('button', { name: 'Iniciar sesión' }).click()
  await expect(page.getByRole('heading', { name: 'Resumen' })).toBeVisible()
  const before = await (await page.request.get('/api/statistics/summary')).json()
  const csrf = (await page.context().cookies()).find(cookie => cookie.name === 'OPOMATIC_CSRF')!.value
  const headers = { 'X-CSRF-Token': csrf }
  const topicResponse = await page.request.post('/api/topics', { headers, data: { name: 'Tema progreso P12' } })
  expect(topicResponse.status()).toBe(201)
  const topic = await topicResponse.json()
  const questionResponse = await page.request.post('/api/questions', { headers, data: {
    topicId: topic.id, statement: 'Pregunta de progreso P12',
    options: [1, 2, 3, 4].map(position => ({ position, text: 'Respuesta progreso ' + position, isCorrect: position === 1 })),
  } })
  expect(questionResponse.status()).toBe(201)
  const question = await questionResponse.json()
  const generated = await (await page.request.post('/api/tests/generate', { headers,
    data: { topicIds: [topic.id], numberOfQuestions: 1 } })).json()
  for (let i = 0; i < 20; i++) {
    expect((await page.request.post('/api/tests/finish', { headers, data: {
      submissionId: randomUUID(), testToken: generated.testToken,
      answers: [{ questionId: generated.questions[0].id, selectedOptionId: null }],
    } })).status()).toBe(201)
  }
  await page.goto('/tests/new')
  await page.getByRole('checkbox', { name: /Tema progreso P12/ }).check()
  await page.getByLabel('Número de preguntas').fill('1')
  await page.getByRole('button', { name: 'Comenzar test' }).click()
  await page.getByRole('radio', { name: /Respuesta progreso 1/ }).check()
  await page.getByRole('button', { name: 'Revisar y finalizar' }).click()
  await page.getByRole('button', { name: 'Confirmar entrega' }).click()
  await expect(page.getByRole('heading', { name: 'Nota 10.00', exact: true })).toBeVisible()
  const detailUrl = page.url()
  expect((await page.request.patch('/api/questions/' + question.id + '/status', { headers, data: { isActive: false } })).status()).toBe(204)
  expect((await page.request.put('/api/topics/' + topic.id, { headers, data: { name: 'Nombre posterior P12' } })).status()).toBe(200)
  expect((await page.request.patch('/api/topics/' + topic.id + '/status', { headers, data: { isActive: false } })).status()).toBe(204)
  await page.goto('/attempts')
  await expect(page.locator('.attempt-list > li')).toHaveCount(20)
  const next = page.getByRole('button', { name: 'Siguiente', exact: true })
  await next.focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/attempts\?page=2$/)
  await expect(page.getByText('Página 2 de 2')).toBeVisible()
  await expect(page.locator('.attempt-list > li')).toHaveCount(before.completedTests + 1)
  await expect(next).toBeDisabled()
  await page.reload()
  await expect(page.getByText('Página 2 de 2')).toBeVisible()
  await page.getByRole('button', { name: 'Anterior', exact: true }).click()
  await expect(page.locator('.attempt-list > li')).toHaveCount(20)
  await page.locator('.attempt-list a').first().click()
  await expect(page).toHaveURL(detailUrl)
  await expect(page.getByRole('heading', { name: 'Pregunta de progreso P12', exact: true })).toBeVisible()
  await expect(page.getByText('Respuesta correcta', { exact: true })).toBeVisible()
  await page.goto('/')
  await expect(page.getByText('Tests terminados').locator('..').getByText(String(before.completedTests + 21), { exact: true })).toBeVisible()
  await expect(page.getByText('Preguntas contestadas').locator('..').getByText(String(before.answeredQuestions + 1), { exact: true })).toBeVisible()
  const after = await (await page.request.get('/api/statistics/summary')).json()
  expect(after.correctCount).toBe(before.correctCount + 1)
  expect(after.unansweredCount).toBe(before.unansweredCount + 20)
  await page.goto('/statistics')
  const row = page.getByRole('row', { name: /Tema progreso P12/ })
  await expect(row).toContainText('100.00 %')
  await expect(row).toContainText('Muestra pequeña')
  await expect(page.getByText('Nombre posterior P12', { exact: true })).toHaveCount(0)
  await page.getByLabel('Orden').selectOption('worst')
  await expect(row).toBeVisible()
  await page.setViewportSize({ width: 320, height: 720 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)).toBe(false)
  // Hold an actual PHP response to verify loading, then test network error feedback.
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/attempts?*', async route => { await gate; await route.continue() })
  await page.goto('/attempts')
  await expect(page.getByRole('status')).toContainText('Cargando historial')
  release()
  await expect(page.locator('.attempt-list > li')).toHaveCount(20)
  await page.unroute('**/api/attempts?*')
  await page.route('**/api/attempts?*', route => route.abort())
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('No se ha podido cargar el historial')
  await page.unroute('**/api/attempts?*')
  await page.route('**/api/statistics/topics', route => route.abort())
  await page.goto('/statistics')
  await expect(page.getByRole('alert')).toContainText('No se han podido cargar las estadísticas por tema')
  await page.unroute('**/api/statistics/topics')
  await page.route('**/api/statistics/summary', route => route.abort())
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('No se han podido cargar tus estadísticas')
})
