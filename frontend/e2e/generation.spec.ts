import { expect, test } from '@playwright/test'
import type { GeneratedTest } from '../src/features/tests/api/testsApi'

test('P09: generate against PHP, navigate, retain answers, abandon and lose progress on reload', async ({ page }) => {
  await page.goto('/tests/new')
  await page.getByLabel('Nombre de usuario').fill('Gogloglo')
  await page.getByLabel('Contraseña').fill(process.env.OPOMATIC_E2E_GOGLOGLO_PASSWORD ?? '')
  await page.getByRole('button', { name: 'Iniciar sesión' }).click()
  await expect(page.getByRole('heading', { name: 'Nuevo test', exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: /Tema P09 navegador/ })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: /Tema P09 oculto/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Comenzar test' }).click()
  await expect(page.getByRole('alert')).toContainText('Selecciona al menos un tema.')
  await page.getByRole('checkbox', { name: /Tema P09 navegador/ }).check()
  await expect(page.getByText('2 preguntas disponibles', { exact: true })).toBeVisible()
  await page.getByLabel('Número de preguntas').fill('201')
  await page.getByRole('button', { name: 'Comenzar test' }).click()
  await expect(page.getByRole('alert')).toContainText('entre 1 y 200')
  await page.getByLabel('Número de preguntas').fill('3')
  await page.getByRole('button', { name: 'Comenzar test' }).click()
  await expect(page.getByRole('alert')).toContainText('solo hay 2 disponibles')
  // Content can change after topics load: the real PHP 409 updates the form.
  const topicsResponse = await page.request.get('/api/topics')
  const topic = (await topicsResponse.json()).find((item: { name: string }) => item.name === 'Tema P09 navegador')
  const listResponse = await page.request.get('/api/questions?topicId=' + topic.id)
  const questionId = (await listResponse.json()).items[0].id
  const csrf = (await page.context().cookies()).find(cookie => cookie.name === 'OPOMATIC_CSRF')!.value
  const statusUrl = '/api/questions/' + questionId + '/status'
  expect((await page.request.patch(statusUrl, { headers: { 'X-CSRF-Token': csrf }, data: { isActive: false } })).status()).toBe(204)
  await page.getByLabel('Número de preguntas').fill('2')
  await page.getByRole('button', { name: 'Comenzar test' }).click()
  await expect(page.getByRole('alert')).toContainText('solo hay 1 disponibles')
  expect((await page.request.patch(statusUrl, { headers: { 'X-CSRF-Token': csrf }, data: { isActive: true } })).status()).toBe(204)
  await page.route('**/api/tests/generate', async route => {
    await new Promise(resolve => setTimeout(resolve, 400))
    await route.continue()
  })
  const generatedResponse = page.waitForResponse(response => response.url().endsWith('/api/tests/generate') && response.status() === 200)
  await page.getByRole('button', { name: 'Comenzar test' }).click()
  await expect(page.getByRole('button', { name: 'Preparando test…' })).toBeDisabled()
  const generated: GeneratedTest = await (await generatedResponse).json()
  expect(generated.questions).toHaveLength(2)
  expect(new Set(generated.questions.map(question => question.id)).size).toBe(2)
  expect(JSON.stringify(generated)).not.toContain('isCorrect')
  expect(generated.testToken).toMatch(/^v1\./)
  await expect(page.getByRole('heading', { name: 'Pregunta 1 de 2' })).toBeVisible()
  await expect(page.getByRole('group')).toHaveAccessibleName(generated.questions[0].statement)
  await expect(page.getByRole('radio')).toHaveCount(4)
  for (const [index, option] of generated.questions[0].options.entries()) {
    await expect(page.getByRole('radio').nth(index)).toHaveAccessibleName(option.text)
  }
  await page.getByRole('radio').nth(1).check()
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pregunta 2 de 2' })).toBeVisible()
  await expect(page.getByRole('group')).toHaveAccessibleName(generated.questions[1].statement)
  await page.getByRole('button', { name: 'Anterior', exact: true }).click()
  await expect(page.getByRole('radio').nth(1)).toBeChecked()
  await page.getByRole('button', { name: 'Dejar sin contestar' }).click()
  await expect(page.getByRole('radio').nth(1)).not.toBeChecked()
  await page.getByRole('button', { name: 'Ir a la pregunta 2, sin contestar' }).click()
  await expect(page.getByRole('heading', { name: 'Pregunta 2 de 2' })).toBeVisible()
  expect(await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length }))).toEqual({ local: 0, session: 0 })
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Nuevo test', exact: true })).toBeVisible()
  await expect(page.getByRole('alert')).toContainText('El test anterior ya no está disponible')
  await page.getByRole('checkbox', { name: /Tema P09 navegador/ }).check()
  await page.getByLabel('Número de preguntas').fill('1')
  await page.getByRole('button', { name: 'Comenzar test' }).click()
  await expect(page.getByRole('heading', { name: 'Pregunta 1 de 1' })).toBeVisible()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: 'Abandonar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pregunta 1 de 1' })).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Abandonar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Nuevo test', exact: true })).toBeVisible()
})
